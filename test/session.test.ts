import {mkdtempSync, writeFileSync, rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {afterEach, describe, expect, it} from 'vitest';
import {Checkpoints, Inbox} from '../src/inbox.ts';
import {hasDurableBatch} from '../src/handoff.ts';
const cleanups: Array<() => void> = [];
afterEach(() => { for (const cleanup of cleanups.splice(0)) cleanup(); });
describe('session storage and handoff', () => {
  it('bounds an in-memory inbox without losing accepted items', () => {
    const inbox = new Inbox();
    const item = {server: 'test', watch: 'watch', observation: {type: 'gap' as const, cursor: null}};
    for (let i = 0; i < 100; i++) inbox.accept(item);
    expect(() => inbox.accept(item)).toThrow('full');
    expect(inbox.size).toBe(100);
    inbox.acknowledge(50);
    inbox.accept(item);
    expect(inbox.size).toBe(51);
    const checkpoints = new Checkpoints();
    checkpoints.set('watch', 'memory');
    expect(checkpoints.get('watch')).toBe('memory');
    expect(new Checkpoints().get('watch')).toBeNull();
  });
  it('keeps accepted observations across restarts until their Pi message is acknowledged', () => {
    const directory = mkdtempSync(join(tmpdir(), 'pi-events-inbox-'));
    cleanups.push(() => rmSync(directory, {recursive: true, force: true}));
    const path = join(directory, 'inbox.json');
    const item = {server: 'test', watch: 'watch', observation: {type: 'gap' as const, cursor: 'a'}};
    const inbox = new Inbox(path);
    inbox.accept(item);
    expect(inbox.snapshot()).toEqual([item]);
    const resumed = new Inbox(path);
    expect(resumed.snapshot()).toEqual([item]);
    resumed.accept({...item, observation: {type: 'gap', cursor: 'b'}});
    resumed.acknowledge(1);
    expect(new Inbox(path).snapshot()).toEqual([{...item, observation: {type: 'gap', cursor: 'b'}}]);
    const checkpointPath = join(directory, 'cursors.json');
    const checkpoints = new Checkpoints(checkpointPath);
    checkpoints.set('subscription', 'quiet-checkpoint');
    expect(new Checkpoints(checkpointPath).get('subscription')).toBe('quiet-checkpoint');
    checkpoints.set('subscription', null);
    expect(new Checkpoints(checkpointPath).get('subscription')).toBe(null);
    checkpoints.set('old-watch', 'old');
    checkpoints.set('current-watch', 'current');
    checkpoints.retain(['current-watch']);
    const pruned = new Checkpoints(checkpointPath);
    expect(pruned.get('old-watch')).toBeNull();
    expect(pruned.get('current-watch')).toBe('current');
  });
  it('requires a persisted custom-message record before acknowledging a batch', async () => {
    const directory = mkdtempSync(join(tmpdir(), 'events-handoff-'));
    cleanups.push(() => rmSync(directory, {recursive: true, force: true}));
    const path = join(directory, 'session.jsonl');
    expect(await hasDurableBatch(path, 'batch')).toBe(false);
    writeFileSync(path, JSON.stringify({type: 'message', message: {content: 'batch'}}) + '\n');
    expect(await hasDurableBatch(path, 'batch')).toBe(false);
    writeFileSync(path, JSON.stringify({type: 'custom_message', customType: 'mcp-events', details: {batchId: 'batch'}}) + '\n');
    expect(await hasDurableBatch(path, 'batch')).toBe(true);
  });
});
